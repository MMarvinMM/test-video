package com.chinatower.order.util;

import com.chinatower.platform.common.utils.Threads;
import com.chinatower.platform.common.utils.spring.SpringUtils;

import java.util.TimerTask;
import java.util.concurrent.ScheduledExecutorService;
import java.util.concurrent.TimeUnit;

/**
 * 异步任务管理器
 *
 * @author chinatower
 */
public class AsyncUtils {

    /**
     * 操作延迟10毫秒
     */
    private final int OPERATE_DELAY_TIME = 100;

    /**
     * 异步操作任务调度线程池
     */
    private ScheduledExecutorService executor = SpringUtils.getBean("scheduledExecutorService");

    /**
     * 单例模式
     */
    private AsyncUtils(){}

    private static AsyncUtils me = new AsyncUtils();

    public static AsyncUtils me()
    {
        return me;
    }

    /**
     * 执行任务
     *
     * @param task 任务
     */
    public void execute(TimerTask task)
    {
        executor.schedule(task, OPERATE_DELAY_TIME, TimeUnit.MILLISECONDS);
    }

    /**
     * 停止任务线程池
     */
    public void shutdown()
    {
        Threads.shutdownAndAwaitTermination(executor);
    }
}
